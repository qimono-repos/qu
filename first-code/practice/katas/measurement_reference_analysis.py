"""Print the Measurements reference data without naming quiz exercises.

The counts below are transcribed from the MIT xPRO reference table. They are
observed counts from that supplied experiment, not results generated by this
noiseless QASM simulator. The circuit maps q[0] -> c[2], q[1] -> c[0], and
q[2] -> c[1].

Convention used by the course exercise:
- quantum ket: |q[0] q[1] q[2]>
- classical label: c[2] c[1] c[0] (c[0] is the rightmost displayed bit)

Run with: python measurement_reference_analysis.py
"""

# Observed classical labels and counts from the course's reference table.
observed_counts = {
    "000": 7939,
    "001": 113,
    "010": 135,
    "011": 3,
    "100": 11,
}

# Each entry is the classical destination for the corresponding qubit index.
qubit_to_classical = {0: 2, 1: 0, 2: 1}


def classical_label_for_state(state: str) -> str:
    """Map a ket written as |q[0] q[1] q[2]> to c[2]c[1]c[0]."""
    if len(state) != 3 or any(bit not in "01" for bit in state):
        raise ValueError("state must be a three-bit string in q[0], q[1], q[2] order")

    q = {index: int(bit) for index, bit in enumerate(state)}
    c = {classical_index: q[qubit_index]
         for qubit_index, classical_index in qubit_to_classical.items()}
    return "".join(str(c[index]) for index in (2, 1, 0))


def main() -> None:
    print("Reference measurement data (source: supplied course table)")
    print("Quantum state |q[0] q[1] q[2]> -> classical label c[2]c[1]c[0] -> observed count")
    print("-" * 82)

    for state in ("001", "010", "011", "100"):
        label = classical_label_for_state(state)
        count = observed_counts.get(label, 0)
        print(f"|{state}> -> {label} -> {count}")

    total_shots = sum(observed_counts.values())
    print("-" * 82)
    print(f"Total observations in reference table: {total_shots}")
    print("Note: these are transcribed reference counts, not a fresh simulator run.")


if __name__ == "__main__":
    main()
